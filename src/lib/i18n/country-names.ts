export function getCountryName(code: string, locale: string): string {
  if (locale === 'th') {
    return THAI_COUNTRY_NAMES[code] ?? code;
  }
  return undefined as unknown as string; // caller falls back to English name
}

export function getDisplayName(code: string, englishName: string, locale: string): string {
  if (locale === 'th') {
    return THAI_COUNTRY_NAMES[code] ?? englishName;
  }
  return englishName;
}

export function searchCountries(
  countries: Array<{iso31661: string; name: string}>,
  query: string,
  locale: string,
) {
  const q = query.toLowerCase();
  return countries.filter((c) => {
    const displayName = getDisplayName(c.iso31661, c.name, locale);
    return (
      displayName.toLowerCase().includes(q) ||
      c.name.toLowerCase().includes(q) ||
      c.iso31661.toLowerCase().includes(q)
    );
  });
}
